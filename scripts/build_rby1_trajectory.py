"""Keep a Phorce photo sweep's timing while replacing its joint targets.

The input schedule is the sidecar generated by build_motion_slots.py.  It
contains the original entry/travel/dwell/home timing, but not a transferable
kinematic path.  Provide one calibrated RB-Y1 right-arm target per dwell label
and a home target; this script emits the JSON consumed by Rby1Robot.

Example:
  python3 scripts/build_rby1_trajectory.py \
    --schedule calibration/slots/motion_04.schedule.json \
    --targets calibration/rby1/full-body-targets.json \
    --out calibration/rby1/frame.full_body.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load_targets(path: Path) -> dict[str, list[float]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError("targets 파일은 label → 7축 rad 배열 JSON 객체여야 합니다")
    targets: dict[str, list[float]] = {}
    for label, values in raw.items():
        if not isinstance(values, list) or len(values) != 7:
            raise ValueError(f"{label}: RB-Y1 오른팔 7축(rad) 값이 필요합니다")
        targets[str(label)] = [float(value) for value in values]
    if "home" not in targets:
        raise ValueError("targets 파일에는 home 값이 필요합니다")
    return targets


def build(schedule: dict, targets: dict[str, list[float]]) -> dict:
    shots = schedule.get("shots", [])
    if not shots:
        raise ValueError("schedule에 촬영 정지 구간이 없습니다")
    total = float(schedule["total_seconds"])
    segments: list[dict] = []
    previous_end = 0.0
    previous_label: str | None = None

    for shot in shots:
        label = str(shot["label"])
        if label not in targets:
            raise ValueError(f"targets 파일에 {label!r} 웨이포인트가 없습니다")
        start, end = float(shot["window_start_s"]), float(shot["window_end_s"])
        if not (0 <= previous_end <= start < end <= total):
            raise ValueError(f"schedule의 시간 순서가 잘못되었습니다: {label}")
        if start > previous_end:
            segments.append(
                {
                    "kind": "entry" if previous_label is None else "travel",
                    "label": "entry" if previous_label is None else f"{previous_label}-to-{label}",
                    "duration_s": round(start - previous_end, 3),
                    "right_arm_rad": targets[label],
                }
            )
        segments.append(
            {
                "kind": "dwell",
                "label": label,
                "duration_s": round(end - start, 3),
                "right_arm_rad": targets[label],
            }
        )
        previous_end, previous_label = end, label

    if total > previous_end:
        segments.append(
            {
                "kind": "home",
                "label": "home",
                "duration_s": round(total - previous_end, 3),
                "right_arm_rad": targets["home"],
            }
        )
    return {"name": str(schedule.get("name", "RB-Y1 photo sweep")), "segments": segments}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schedule", type=Path, required=True)
    parser.add_argument("--targets", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    output = build(
        json.loads(args.schedule.read_text(encoding="utf-8")),
        load_targets(args.targets),
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(output, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"RB-Y1 trajectory 생성: {args.out}")


if __name__ == "__main__":
    main()
